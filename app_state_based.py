
"""
Gradio-based user interface for the second AI Escape Room implementation.

In this version, Python is responsible for validating player actions,
maintaining game progress, and enforcing the puzzle sequence. Gemini
is used to interpret commands and produce descriptive game responses.

Start the interface directly with:

    python app_v2.py

Alternatively, use the main project launcher:

    python run.py v2

Both API-connected and standalone offline modes are supported.
"""

import gradio as gr

from escape_room.gemini_client import GeminiLLM
from escape_room.v2.game_controller import GameV2
from escape_room.v2.intent_parser import empty_intent
from escape_room.v2.game_state import summary


WELCOME_TEXT = """
# AI Escape Room – Version 2

*Python manages the game mechanics, while the LLM brings the story to life.*

You are trapped inside an old library. Explore your surroundings,
inspect objects, collect useful items, and solve the clues to discover
the combination that unlocks the exit.
"""


def get_game_mode(session):
    """Identify whether the current session is using online or offline mode."""

    if session.online:
        selected_model = session.llm.models[0]
        return f"Mode: **online** (Gemini - {selected_model})"

    return (
        "Mode: **offline** "
        "(no API key - regex parser and plain narration)"
    )


def initialize_session():
    """Create a game instance and generate the initial interface contents."""

    game = GameV2(GeminiLLM())

    initial_messages = [
        {
            "role": "assistant",
            "content": game.intro(),
        }
    ]

    game_status = summary(game.state)
    mode_information = get_game_mode(game)

    return game, initial_messages, game_status, mode_information


def update_conversation(session, conversation, action,
                        intent=None, include_action=True):
    """Run a requested action and update the conversation with its result."""

    game_response, _, _ = session.turn(action, intent)

    # Copy the existing messages before adding new conversation entries.
    chat_messages = conversation.copy()

    # Only display a user message when the player explicitly entered it.
    if include_action:
        chat_messages.append(
            {
                "role": "user",
                "content": action,
            }
        )

    # Add the response generated by the game.
    chat_messages.append(
        {
            "role": "assistant",
            "content": game_response,
        }
    )

    return chat_messages


def handle_player_action(message, conversation, session):
    """Handle player input and synchronize the conversation and game status."""

    # Ignore blank submissions without advancing the game.
    if not message.strip():
        return "", conversation, session, summary(session.state)

    updated_chat = update_conversation(
        session,
        conversation,
        message,
    )

    refreshed_status = summary(session.state)

    return "", updated_chat, session, refreshed_status


def display_inventory(conversation, session):
    """Retrieve the current inventory and display it in the chat window."""

    chat_messages = update_conversation(
        session,
        conversation,
        "inventory",
        intent=empty_intent("inventory"),
        include_action=False,
    )

    return (
        chat_messages,
        session,
        summary(session.state),
    )


def request_hint(conversation, session):
    """Execute the hint command and display the resulting guidance."""

    chat_messages = update_conversation(
        session,
        conversation,
        "hint",
        intent=empty_intent("hint"),
        include_action=False,
    )

    return (
        chat_messages,
        session,
        summary(session.state),
    )


def reset_session(session):
    """Start a new game by replacing the current session."""

    # Calling the initialization function also reloads the .env settings.
    return initialize_session()


def create_app():
    """Set up the Gradio interface and connect all interactive controls."""

    with gr.Blocks(title="AI Escape Room - Version 2") as interface:

        gr.Markdown(WELCOME_TEXT)

        # Preserve the game instance between successive user interactions.
        game_state = gr.State()

        with gr.Row():

            # Main column containing the gameplay conversation and controls.
            with gr.Column(scale=3):

                chat_display = gr.Chatbot(
                    height=460,
                    label="Game Master",
                )

                player_command = gr.Textbox(
                    placeholder="e.g. examine the bookshelf",
                    label="What do you do?",
                )

                with gr.Row():

                    send_button = gr.Button(
                        "Send",
                        variant="primary",
                    )

                    inventory_button = gr.Button("Inventory")
                    hint_button = gr.Button("Hint")
                    restart_button = gr.Button("Restart game")

            # Side panel containing progress and execution-mode information.
            with gr.Column(scale=1):

                gr.Markdown("### Game state")

                progress_display = gr.Markdown()
                execution_mode_display = gr.Markdown()

        # Initialize the game when the application is first loaded.
        interface.load(
            initialize_session,
            outputs=[
                game_state,
                chat_display,
                progress_display,
                execution_mode_display,
            ],
        )

        # Process commands entered using the keyboard's Enter key.
        player_command.submit(
            handle_player_action,
            inputs=[
                player_command,
                chat_display,
                game_state,
            ],
            outputs=[
                player_command,
                chat_display,
                game_state,
                progress_display,
            ],
        )

        # Provide an alternative way to submit the current command.
        send_button.click(
            handle_player_action,
            inputs=[
                player_command,
                chat_display,
                game_state,
            ],
            outputs=[
                player_command,
                chat_display,
                game_state,
                progress_display,
            ],
        )

        # Retrieve and display the items collected by the player.
        inventory_button.click(
            display_inventory,
            inputs=[
                chat_display,
                game_state,
            ],
            outputs=[
                chat_display,
                game_state,
                progress_display,
            ],
        )

        # Request guidance without requiring the player to type a command.
        hint_button.click(
            request_hint,
            inputs=[
                chat_display,
                game_state,
            ],
            outputs=[
                chat_display,
                game_state,
                progress_display,
            ],
        )

        # Replace the existing session with a completely new game.
        restart_button.click(
            reset_session,
            inputs=[game_state],
            outputs=[
                game_state,
                chat_display,
                progress_display,
                execution_mode_display,
            ],
        )

    return interface


if __name__ == "__main__":
    application = create_app()
    application.launch()
